"""InventoryRepository live smoke test — NOT run by default.

Manual run (self-cleaning, touches only its own throwaway rows):

    RUN_DB_SMOKE=1 uv run pytest tests/integration/test_inventory_repository_integration.py -v

Requirements:
- Migration 001 applied to Supabase
- .env SUPABASE_DB_URL configured and reachable

Safety:
- Creates one throwaway product + one inventory row (on_hand 100,
  reserved 25), never touches existing records. Cleanup deletes its own
  inventory row first, then its own product.
"""

import os
from uuid import uuid4

import pytest

from app.database.connection import transaction
from app.repositories.inventory import InventoryRepository
from app.schemas.inventory import InventoryResponse

pytestmark = pytest.mark.skipif(
    os.environ.get("RUN_DB_SMOKE") != "1",
    reason="live Supabase smoke test: set RUN_DB_SMOKE=1 to run",
)


def test_inventory_read_roundtrip():
    repo = InventoryRepository()
    prod_id = uuid4()
    sku = f"SMOKE-{prod_id.hex[:8]}"  # unique, products.sku UNIQUE

    inserted = False
    try:
        with transaction() as conn:  # committed insert transaction
            conn.execute(
                "INSERT INTO products (id, sku, name, unit) VALUES (%s, %s, %s, %s)",
                (prod_id, sku, f"Smoke Test Product {prod_id.hex[:6]}", "pcs"),
            )
            conn.execute(
                "INSERT INTO inventory (product_id, on_hand_stock, reserved_stock) "
                "VALUES (%s, %s, %s)",
                (prod_id, 100, 25),
            )
        inserted = True

        inv = repo.get_by_product_id(prod_id)
        assert isinstance(inv, InventoryResponse)
        assert inv.on_hand_stock == 100
        assert inv.reserved_stock == 25
        assert inv.available_stock == 75  # generated by the database

        assert repo.get_by_product_id(uuid4()) is None  # unknown product
    finally:
        if inserted:
            with transaction() as conn:  # cleanup own rows only
                conn.execute("DELETE FROM inventory WHERE product_id = %s", (prod_id,))
                conn.execute("DELETE FROM products WHERE id = %s", (prod_id,))
