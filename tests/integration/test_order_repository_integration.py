"""OrderRepository live smoke test — NOT run by default.

Manual run (self-cleaning, touches only its own throwaway rows):

    RUN_DB_SMOKE=1 uv run pytest tests/integration/test_order_repository_integration.py -v

Requirements:
- Migration 001 applied to Supabase
- .env SUPABASE_DB_URL configured and reachable

Safety:
- Creates one throwaway customer, two throwaway products, one draft order
  with two items (random code/SKU/phone), never reuses or modifies
  existing records, deletes its own rows in teardown (order_items,
  orders, products, customer — FK-safe order; cascade also covers items).
- Draft orders reserve no inventory and consume no credit (migration 001
  business rules), so this test cannot affect stock or balances.
- Every repository call receives the connection from transaction() —
  the repository itself never commits or rolls back.
"""

import os
import re
from decimal import Decimal
from uuid import uuid4

import pytest

from app.database.connection import transaction
from app.repositories.order import OrderRepository
from app.schemas.order import (
    OrderCreate,
    OrderDetailResponse,
    OrderItemCreate,
    OrderItemInsert,
    OrderResponse,
    OrderStatus,
)

pytestmark = pytest.mark.skipif(
    os.environ.get("RUN_DB_SMOKE") != "1",
    reason="live Supabase smoke test: set RUN_DB_SMOKE=1 to run",
)


def test_order_create_and_get_by_id_roundtrip():
    repo = OrderRepository()
    cust_id = uuid4()
    p1, p2 = uuid4(), uuid4()
    code = f"SMOKE-{cust_id.hex[:8]}"
    # numeric-only: UUID hex can contain a-f, which the E.164 CHECK rejects.
    phone = f"+62899{cust_id.int % 1_000_000_000:09d}"

    inserted = False
    order_id = None
    try:
        with transaction() as conn:  # throwaway FK parents
            conn.execute(
                "INSERT INTO customers (id, code, name, phone) VALUES (%s, %s, %s, %s)",
                (cust_id, code, "Smoke Order Customer", phone),
            )
            conn.execute(
                "INSERT INTO products (id, sku, name, unit) VALUES (%s, %s, %s, %s)",
                (p1, f"SMOKE-{p1.hex[:8]}", "Smoke Order Product 1", "pcs"),
            )
            conn.execute(
                "INSERT INTO products (id, sku, name, unit) VALUES (%s, %s, %s, %s)",
                (p2, f"SMOKE-{p2.hex[:8]}", "Smoke Order Product 2", "carton"),
            )
        inserted = True  # only after the parent transaction committed

        order_create = OrderCreate(
            customer_id=cust_id,
            notes="smoke test order",
            items=[
                OrderItemCreate(product_id=p1, quantity=2),
                OrderItemCreate(product_id=p2, quantity=1),
            ],
        )
        items_in = [
            OrderItemInsert(product_id=p1, quantity=2, unit_price=Decimal("150.00")),
            OrderItemInsert(product_id=p2, quantity=1, unit_price=Decimal("2500.00")),
        ]

        with transaction() as conn:  # one caller-owned transaction, whole draft
            order = repo.create_order(conn, order_create)
            assert isinstance(order, OrderResponse)
            assert order.customer_id == cust_id
            assert re.fullmatch(r"ORD-\d{8}", order.order_number)
            assert order.status is OrderStatus.DRAFT
            assert order.total_amount == Decimal(
                "0.00"
            )  # DB default, service updates later
            assert order.confirmed_at is None and order.delivered_at is None
            order_id = order.id

            items = repo.create_order_items(conn, order.id, items_in)
            assert len(items) == 2
            by_product = {i.product_id: i for i in items}
            # subtotals generated by Postgres, not computed in Python
            assert by_product[p1].subtotal == Decimal("300.00")
            assert by_product[p2].subtotal == Decimal("2500.00")
            assert by_product[p1].unit_price == Decimal("150.00")  # stored snapshot

            detail = repo.get_by_id(conn, order.id)
            assert isinstance(detail, OrderDetailResponse)
            assert detail.id == order.id and detail.order_number == order.order_number
            assert len(detail.items) == 2
            assert {i.subtotal for i in detail.items} == {
                Decimal("300.00"),
                Decimal("2500.00"),
            }

        with transaction() as conn:  # fresh read after commit + typo-safety
            persisted = repo.get_by_id(conn, order_id)
            assert persisted is not None
            assert persisted.order_number == order.order_number
            assert len(persisted.items) == 2
            assert repo.get_by_id(conn, uuid4()) is None
    finally:
        if inserted:
            with transaction() as conn:  # cleanup own rows only, FK-safe order
                conn.execute(
                    "DELETE FROM order_items WHERE order_id IN "
                    "(SELECT id FROM orders WHERE customer_id = %s)",
                    (cust_id,),
                )
                conn.execute("DELETE FROM orders WHERE customer_id = %s", (cust_id,))
                conn.execute("DELETE FROM products WHERE id IN (%s, %s)", (p1, p2))
                conn.execute("DELETE FROM customers WHERE id = %s", (cust_id,))
